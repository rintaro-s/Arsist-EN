import { describe, expect, it } from 'vitest';
import fs from 'fs';
import path from 'path';
import { BUILTIN_SPACES, findBuiltinSpace } from './spaces';
import { solveAll, solvePlacement, thingSize, worldFromSpace, placementOrder, type SolveResult } from './solver';
import { vocabularyForRuntime } from './vocabulary';
import type { Thing } from './types';

/**
 * 置き方の計算の表 (solver-cases.json)。C# の写し (Runtime/Spatial/Core/PlacementSolver.cs) も
 * tools/perception-check の SpatialChecks で同じ表を解き、同じ答えになることを確かめる。
 * 計算を変えたら、UPDATE_SOLVER_CASES=1 npx vitest run src/shared/layster/spatial/solver.test.ts で表を作り直し、
 * 差分 (どの物がどこへ動いたか) を読んでから入れる。
 */
const CASES_FILE = path.join(__dirname, 'solver-cases.json');

/** 表に使う、よくある置き方を一通り含んだアプリ。 */
const SAMPLE_THINGS: Thing[] = [
  {
    id: 'quiz',
    visual: { kind: 'panel', size: [0.4, 0.25], items: [{ type: 'text', text: 'x + 3 = 5' }] },
    place: {
      on: { is: ['table'] }, distance: [0.3, 1.6], clearance: [0.45, 0.3], facing: 'user',
      fallback: [
        { on: { has: ['support'] }, distance: [0.3, 2.0], height: [0.3, 1.3] },
        { at: { frame: 'user', at: [0, 1.0, 0.75] } },
      ],
    },
  },
  {
    id: 'buddy',
    visual: { kind: 'character', file: 'Assets/Characters/buddy.vrm', height: 1.5 },
    place: { near: { user: 'feet' }, around: [0.9, 1.6], prefer: 'closest', avoid: ['quiz'], facing: 'user' },
  },
  {
    id: 'poster',
    visual: { kind: 'panel', size: [0.6, 0.4], items: [] },
    place: { on: { is: ['wall'] }, distance: [0.5, 3.5], prefer: 'inView', fallback: [{ near: { user: 'head' }, around: [1.2, 1.2] }] },
  },
  {
    id: 'tag',
    visual: { kind: 'label', text: 'hint', height: 0.04 },
    place: { near: { thing: 'quiz' }, around: [0.3, 0.5], height: [0.75, 1.5] },
  },
  {
    id: 'hud',
    visual: { kind: 'panel', size: [0.5, 0.1], items: [] },
    place: { mode: 'head', at: { frame: 'head', at: [0, -0.25, 1.4] } },
  },
];

function rounded(results: SolveResult[]) {
  return results.map((r) => ({ thing: r.thing, rule: r.rule, host: r.host ?? null, frame: r.frame, at: r.pose.at, yaw: r.pose.yaw }));
}

function buildCases() {
  return BUILTIN_SPACES.map((space) => {
    const world = worldFromSpace(space);
    return {
      name: space.id,
      user: world.user,
      hands: world.hands,
      entities: space.entities,
      things: SAMPLE_THINGS,
      expected: rounded(solveAll(SAMPLE_THINGS, world)),
    };
  });
}

describe('spatial solver', () => {
  it('matches the shared table (solver-cases.json)', () => {
    const cases = buildCases();
    if (process.env.UPDATE_SOLVER_CASES === '1' || !fs.existsSync(CASES_FILE)) {
      fs.writeFileSync(CASES_FILE, JSON.stringify({
        note: 'Generated by solver.test.ts (UPDATE_SOLVER_CASES=1). Checked by vitest and tools/perception-check SpatialChecks.',
        vocabulary: vocabularyForRuntime(),
        cases,
      }, null, 1) + '\n');
    }
    const stored = JSON.parse(fs.readFileSync(CASES_FILE, 'utf8'));
    expect(stored.cases.map((c: { expected: unknown }) => c.expected)).toEqual(cases.map((c) => c.expected));
  });

  it('puts the quiz on a table where there is one, and falls back where there is none', () => {
    const seated = solveAll(SAMPLE_THINGS, worldFromSpace(findBuiltinSpace('desk-front')!));
    const quiz = seated.find((r) => r.thing === 'quiz')!;
    expect(quiz.rule).toBe(0);
    expect(quiz.host).toBe('desk');

    // ワンルームの机は 2 m 以上先 (distance の外) → 次の規則で、近くの載せられる面 (ベッド)
    const studio = solveAll(SAMPLE_THINGS, worldFromSpace(findBuiltinSpace('studio')!));
    expect(studio.find((r) => r.thing === 'quiz')!).toMatchObject({ rule: 1, host: 'bed' });

    const noScan = solveAll(SAMPLE_THINGS, worldFromSpace(findBuiltinSpace('no-scan')!));
    const q2 = noScan.find((r) => r.thing === 'quiz')!;
    // 机も載せられる面も無い (床は高さ 0.3〜1.3 に合わない) → 最後の fallback (ユーザーの前)
    expect(q2.rule).toBe(2);
    expect(q2.notes.length).toBe(2);
  });

  it('never places anything behind a wall or inside furniture', () => {
    for (const space of BUILTIN_SPACES) {
      const world = worldFromSpace(space);
      for (const r of solveAll(SAMPLE_THINGS, world)) {
        if (r.frame !== 'world' || r.rule === 'default') continue;
        // 物の中心が、どの壁の裏にも無い
        for (const e of space.entities.filter((x) => x.is[0] === 'wall')) {
          const yaw = ((e.yaw ?? 0) * Math.PI) / 180;
          const dx = r.pose.at[0] - e.at[0];
          const dz = r.pose.at[2] - e.at[2];
          const lx = dx * Math.cos(-yaw) + dz * Math.sin(-yaw);
          const lz = -dx * Math.sin(-yaw) + dz * Math.cos(-yaw);
          if (Math.abs(lx) <= e.size[0] / 2 && r.pose.at[1] < e.at[1] + e.size[1] / 2) {
            expect(lz, `${space.id}/${r.thing} behind ${e.id}`).toBeGreaterThan(-0.03);
          }
        }
      }
    }
  });

  it('faces the user', () => {
    const r = solvePlacement('p', [0.4, 0.3, 0.01], { at: { frame: 'user', at: [1, 1.2, 1] } }, worldFromSpace(findBuiltinSpace('open-floor')!));
    // (1, 1) にある物から原点を向く = 南西 = -135°
    expect(r.pose.yaw).toBeCloseTo(-135, 3);
  });

  it('keeps head-locked things in the head frame', () => {
    const r = solvePlacement('h', [0.5, 0.1, 0.01], { mode: 'head', at: { frame: 'head', at: [0, -0.25, 1.4] } }, worldFromSpace(findBuiltinSpace('studio')!));
    expect(r.frame).toBe('head');
    expect(r.pose.at).toEqual([0, -0.25, 1.4]);
    expect(Math.abs(r.pose.yaw)).toBeCloseTo(180, 3);
  });

  it('always places something, even with impossible rules', () => {
    const r = solvePlacement('x', [0.3, 0.3, 0.3], { on: { is: ['unicorn'] } }, worldFromSpace(findBuiltinSpace('tiny')!));
    expect(r.rule).toBe('default');
    expect(r.pose.at[2]).toBeGreaterThan(0);
  });

  it('orders things so that referenced ones are placed first', () => {
    const order = placementOrder([
      { id: 'a', visual: { kind: 'marker' }, place: { near: { thing: 'b' } } },
      { id: 'b', visual: { kind: 'marker' }, place: { at: { frame: 'world', at: [0, 1, 1] } } },
    ]);
    expect(order.map((t) => t.id)).toEqual(['b', 'a']);
  });

  it('sizes things from their visual', () => {
    expect(thingSize({ kind: 'panel', size: [0.4, 0.3], items: [] })).toEqual([0.4, 0.3, 0.01]);
    expect(thingSize({ kind: 'character', file: 'x.vrm' })[1]).toBe(1.5);
  });
});
