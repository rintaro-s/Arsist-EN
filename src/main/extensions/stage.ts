/**
 * 拡張機能をビルド用の Unity プロジェクトに入れるための、生成物と書き換え。
 *
 * ファイルの出し入れ (UnityBuilder.stageExtensions) とは分けて、ここは入力 → 文字列の
 * 純粋な関数だけにしてある (vitest で中身まで確かめられるように)。
 *
 * Unity プロジェクトの中の置き場:
 *   Assets/ArsistExtensions/<id>/Runtime/...       拡張機能の Runtime/ の写し
 *   Assets/ArsistExtensions/<id>/Editor/...        拡張機能の Editor/ の写し (Unity は "Editor" フォルダをビルドに入れない)
 *   Assets/ArsistExtensions/ArsistExtensionRegistry.g.cs   入口のクラスを new する登録コード
 *   Assets/ArsistExtensions/link.xml               IL2CPP に消させない名前空間
 */
import type { ExtensionManifest, ResolvedExtension } from '../../shared/extensions';

export const EXTENSIONS_ASSET_DIR = 'ArsistExtensions';
export const REGISTRY_FILE = 'ArsistExtensionRegistry.g.cs';

/** 実機の登録コード。拡張機能が 1 つも無ければ空文字 (ファイルを置かない)。 */
export function renderRegistrySource(active: Array<Pick<ResolvedExtension, 'manifest'>>): string {
  const entries = active
    .map((a) => a.manifest)
    .filter((m): m is ExtensionManifest & { unity: { entry: string } } => !!m.unity?.entry)
    .sort((a, b) => a.id.localeCompare(b.id));
  if (entries.length === 0) return '';

  const lines = entries.map((m) => `            Arsist.Runtime.Extensions.ArsistExtensions.Register(new global::${m.unity.entry}()); // ${m.id} ${m.version}`);
  return [
    '// <auto-generated>',
    '// Generated by Arsist (src/main/extensions/stage.ts) for this build. Do not edit:',
    '// it is rewritten on every build from the enabled extensions (Extensions/<id>/extension.json).',
    '// </auto-generated>',
    '',
    'namespace Arsist.Generated',
    '{',
    '    internal static class ArsistExtensionRegistry',
    '    {',
    '        // Runs before any scene object wakes up, so ScriptEngineManager.Awake already sees the extensions.',
    '        [UnityEngine.Scripting.Preserve]',
    '        [UnityEngine.RuntimeInitializeOnLoadMethod(UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]',
    '        private static void Register()',
    '        {',
    ...lines,
    '        }',
    '    }',
    '}',
    '',
  ].join('\n');
}

/** 名前空間 (unity.preserve、無ければ entry の名前空間)。 */
export function preservedNamespaces(active: Array<Pick<ResolvedExtension, 'manifest'>>): string[] {
  const out = new Set<string>();
  for (const { manifest } of active) {
    const listed = manifest.unity?.preserve ?? [];
    if (listed.length > 0) listed.forEach((ns) => out.add(ns));
    else if (manifest.unity?.entry) out.add(manifest.unity.entry.split('.').slice(0, -1).join('.'));
  }
  return [...out].filter(Boolean).sort();
}

/**
 * link.xml。拡張機能のスクリプト API は Jint がリフレクションで呼ぶので、IL2CPP の
 * 削除から守らないと、実機でだけメソッドが消える (エラーにならず undefined になる)。
 */
export function renderLinkXml(active: Array<Pick<ResolvedExtension, 'manifest'>>): string {
  const namespaces = preservedNamespaces(active);
  if (namespaces.length === 0) return '';
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by Arsist for the enabled extensions. Rewritten on every build. -->',
    '<linker>',
    '  <assembly fullname="Assembly-CSharp">',
    ...namespaces.map((ns) => `    <namespace fullname="${ns}" preserve="all" />`),
    '  </assembly>',
    '</linker>',
    '',
  ].join('\n');
}

export interface AndroidManifestAdditions {
  permissions: string[];
  features: Array<{ name: string; required: boolean }>;
  metadata: Array<{ name: string; value: string }>;
}

/** 有効な拡張機能が要る Android の宣言を集める (重複は落とす)。 */
export function collectAndroidAdditions(active: Array<Pick<ResolvedExtension, 'manifest'>>): AndroidManifestAdditions {
  const permissions = new Set<string>();
  const features = new Map<string, boolean>();
  const metadata = new Map<string, string>();
  for (const { manifest } of active) {
    manifest.android?.permissions?.forEach((p) => permissions.add(p));
    for (const f of manifest.android?.features ?? []) {
      // どれか 1 つが必須と言えば必須
      features.set(f.name, (features.get(f.name) ?? false) || f.required === true);
    }
    for (const m of manifest.android?.metadata ?? []) metadata.set(m.name, m.value);
  }
  return {
    permissions: [...permissions].sort(),
    features: [...features].map(([name, required]) => ({ name, required })).sort((a, b) => a.name.localeCompare(b.name)),
    metadata: [...metadata].map(([name, value]) => ({ name, value })).sort((a, b) => a.name.localeCompare(b.name)),
  };
}

function escapeAttr(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function declares(xml: string, element: string, name: string): boolean {
  const re = new RegExp(`<${element}\\b[^>]*android:name\\s*=\\s*"${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`);
  return re.test(xml);
}

/**
 * AndroidManifest.xml に足りない宣言だけを足す。既にあるものには触れない
 * (アダプタの manifest が決めた値を、拡張機能が黙って変えないように)。
 */
export function mergeAndroidManifest(xml: string, additions: AndroidManifestAdditions): { xml: string; added: string[] } {
  const added: string[] = [];
  let out = xml;

  const beforeManifestEnd: string[] = [];
  for (const p of additions.permissions) {
    if (declares(out, 'uses-permission', p)) continue;
    beforeManifestEnd.push(`    <uses-permission android:name="${escapeAttr(p)}" />`);
    added.push(`uses-permission ${p}`);
  }
  for (const f of additions.features) {
    if (declares(out, 'uses-feature', f.name)) continue;
    beforeManifestEnd.push(`    <uses-feature android:name="${escapeAttr(f.name)}" android:required="${f.required}" />`);
    added.push(`uses-feature ${f.name}`);
  }
  if (beforeManifestEnd.length > 0) {
    const end = out.lastIndexOf('</manifest>');
    if (end < 0) throw new Error('AndroidManifest.xml has no </manifest>');
    const block = `    <!-- added by Arsist extensions -->\n${beforeManifestEnd.join('\n')}\n`;
    out = out.slice(0, end) + block + out.slice(end);
  }

  const meta: string[] = [];
  for (const m of additions.metadata) {
    if (declares(out, 'meta-data', m.name)) continue;
    meta.push(`        <meta-data android:name="${escapeAttr(m.name)}" android:value="${escapeAttr(m.value)}" />`);
    added.push(`meta-data ${m.name}`);
  }
  if (meta.length > 0) {
    const end = out.lastIndexOf('</application>');
    if (end < 0) throw new Error('AndroidManifest.xml has no </application> for extension meta-data');
    out = out.slice(0, end) + `        <!-- added by Arsist extensions -->\n${meta.join('\n')}\n    ` + out.slice(end);
  }

  return { xml: out, added };
}

/** Unity に渡す manifest.json の extensions (実機と Editor のフックが読む)。 */
export function manifestEntries(active: ResolvedExtension[]): Array<Record<string, unknown>> {
  return active.map((a) => ({
    id: a.manifest.id,
    version: a.manifest.version,
    dataVersion: a.dataVersion,
    settings: a.settings,
    entry: a.manifest.unity?.entry ?? null,
    scriptGlobals: a.manifest.script?.globals ?? [],
    replaces: a.manifest.replaces ?? [],
  }));
}
